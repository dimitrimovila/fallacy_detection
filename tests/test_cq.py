"""Agreement with missing raters, annotation provenance and probability orientation."""

import numpy as np
import pandas as pd
import pytest

from argfallacy.eval.cq import agreement, tables
from argfallacy.schemes import load_all


def test_nominal_alpha_uses_coincidences_and_omits_singletons():
    result = agreement([["yes", "yes", "no"], ["no", "no", None], ["other", None]])
    assert result["alpha"] == pytest.approx(1 / 3)
    assert result["raw_agreement"] == .5
    assert result["units"] == 2
    assert result["pairs"] == 4
    assert agreement([["yes", "no"], ["yes", "no"]])["alpha"] == -.5
    assert np.isnan(agreement([["yes", "yes"]])["alpha"])
    assert np.isnan(agreement([["yes", None]])["raw_agreement"])


@pytest.fixture
def cq_data():
    scheme = load_all()["analogy"]
    ids = [f"item{i}" for i in range(20)]
    items = pd.DataFrame({"item_id": ids, "gold_scheme": "analogy"})
    rows, notes = [], []
    for ident in ids:
        for cq in scheme.cqs:
            notes.append({"item_id": ident, "annotator": "dumitru", "sheet": "human",
                          "row": 1, "field": cq, "value": "no"})
            for model in ["a", "b"]:
                rows.append({"item_id": ident, "stage": "stage2", "scheme_condition": "gold",
                             "scheme": "analogy", "cq_id": cq, "model": model,
                             "answer": "no", "p_logprob_yes": .2, "p_sample_yes": np.nan,
                             "p_verbal": .3})
    # A verdict annotation is not generated by traversing the model or gold diagram.
    for ident in ids:
        for person, label in [("dumitru", "weak_analogy"), ("enrico", "weak_analogy"),
                              ("eleni", "good_argumentation")]:
            notes.append({"item_id": ident, "annotator": person, "sheet": "verdicts",
                          "row": 1, "field": "verdict", "value": label})
    return pd.DataFrame(rows), items, pd.DataFrame(notes), {"analogy": scheme}, ["a", "b"]


def test_brier_is_already_oriented_and_off_path_flips_have_no_weight(cq_data):
    frames, status = tables(*cq_data)
    cq = frames["cq_metrics"]
    assert np.allclose(cq.p_logprob_brier, .04)
    assert np.allclose(cq.p_verbal_brier, .09)
    assert (cq.annotated == 20).all()
    assert (cq.human_agreement == 1).all()
    off = cq[cq.cq_id == "CQ4"]
    assert (off.reached == 0).all()
    assert (off.weight_on_verdict == 0).all()
    assert frames["cq_calibration"].groupby(["model", "probability"]).size().eq(10).all()
    assert status["conflicting_verdict_ratings_excluded"] == 0
    assert frames["human_agreement"].iloc[0].raw_agreement == pytest.approx(1 / 3)


def test_new_scheme_questions_never_join_original_human_answers(cq_data):
    frames, _ = tables(*cq_data, human_compatible=False)
    assert frames["cq_metrics"].annotated.eq(0).all()
    assert frames["cq_calibration"].empty


def test_missing_prediction_is_a_human_disagreement(cq_data):
    rows, *rest = cq_data
    rows = rows.drop(rows[(rows.model == "a") & (rows.cq_id == "CQ1")].index[:1])
    frames, _ = tables(rows, *rest)
    row = frames["cq_metrics"].query("model == 'a' and cq_id == 'CQ1'").iloc[0]
    assert row.annotated == 20
    assert row.human_agreement == .95
    assert row.missing == 1


def test_conflicting_duplicate_verdicts_are_not_extra_raters(cq_data):
    rows, items, annotations, schemes, entries = cq_data
    extra = annotations[(annotations.field == "verdict") &
                        (annotations.annotator == "dumitru")].iloc[[0]].copy()
    extra["value"] = "good_argumentation"
    frames, status = tables(rows, items, pd.concat([annotations, extra]), schemes, entries)
    assert status["conflicting_verdict_ratings_excluded"] == 1
    assert frames["human_agreement"].iloc[0].pairs == 58


def test_identical_repeated_cq_ratings_count_once_and_conflicts_stop(cq_data):
    from argfallacy.schemes import SchemeError

    rows, items, annotations, schemes, entries = cq_data
    repeated = annotations[annotations.field == "CQ1"].iloc[[0]].copy()
    repeated["row"] = 2
    frames, _ = tables(rows, items, pd.concat([annotations, repeated]), schemes, entries)
    assert frames["cq_metrics"].annotated.eq(20).all()
    repeated["value"] = "yes"
    with pytest.raises(SchemeError, match="Conflicting human CQ"):
        tables(rows, items, pd.concat([annotations, repeated]), schemes, entries)
